/**
 * 한글 검색어로 아이콘 이름 목록을 반환합니다.
 * 부분 일치(키워드에 검색어가 포함되거나, 검색어가 키워드에 포함)를 지원합니다.
 */
export function searchByKorean(query: string): Set<string> {
  const q = query.trim();
  if (!q) return new Set();
  const result = new Set<string>();
  for (const [keyword, icons] of Object.entries(KOREAN_ICON_MAP)) {
    if (keyword.includes(q) || q.includes(keyword)) {
      icons.forEach(seed => {
        // 정확히 매핑된 아이콘 추가
        result.add(seed);
        // 시드 이름을 포함하는 모든 아이콘도 포함 (person → person_add, person_outline…)
        ALL_ICONS.forEach(icon => {
          if (icon.includes(seed)) result.add(icon);
        });
      });
    }
  }
  return result;
}

